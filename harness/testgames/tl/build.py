#!/usr/bin/env python3
"""Build the SynthTl game: the game/*.rpy sources, the tl/fr and tl/de translations, and tl.plan.

    python3 harness/testgames/build.py tl

The plan starts the game, then jumps to each language switch label in turn. Each jump stops on the first line of its
part, so the screenshots show that part's language. Run it stock (eager) and player (deferred); the screenshots must match.
"""
import pathlib
import shutil

HERE = pathlib.Path(__file__).resolve().parent

# (label to jump to, screenshot name)
PARTS = [("to_fr", "03-fr"), ("to_en", "04-en"), ("to_de", "05-de"), ("to_en", "06-en-again")]


def write_plan():
    lines = ["# Generated by build.py. Each jump to a to_* label switches the language, then stops on the first line of",
             "# that part. Screenshots show that language.",
             "wait menu True", "cmd click off", "settle 3", "shot 01-menu",
             "cmd start", "after_start", "cmd advance-to 4", "wait advance-done", "settle 2", "shot 02-start-en"]
    for label, shot in PARTS:
        lines += ["cmd jump %s" % label, "settle 2", "shot %s" % shot]
    lines.append("quit")
    (HERE / "tl.plan").write_text("\n".join(lines) + "\n")


def build(dest):
    write_plan()
    shutil.rmtree(dest / "game", ignore_errors=True)
    shutil.copytree(HERE / "game", dest / "game",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "cache", "saves"))


if __name__ == "__main__":
    import sys
    sys.path.insert(0, str(HERE.parent))
    build(HERE.parent / "build" / "tl")
